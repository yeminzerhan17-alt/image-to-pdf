/**
 * Bundle every source file into one readable document.
 *
 * Makes the whole project viewable/printable/searchable as a single file, which
 * is handy for reviewing the code, pasting it into a chat, or handing it to
 * someone who would rather read one document than click through a tree.
 *
 *   node scripts/bundle-code.mjs         -> CODE.md
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..');
const OUT = join(ROOT, 'CODE.md');

/** Directories to walk, in the order a reader would want them. */
const DIRS = ['src', 'tests', 'scripts', 'public'];

/** Root-level files worth including. */
const ROOT_FILES = [
  'README.md',
  'package.json',
  'tsconfig.json',
  'vite.config.ts',
  'index.html',
  '.gitignore',
];

const SKIP = new Set(['node_modules', 'dist', '.git', 'CODE.md', 'package-lock.json']);

const TEXT_EXTENSIONS = new Set([
  '.ts',
  '.tsx',
  '.js',
  '.mjs',
  '.jsx',
  '.json',
  '.css',
  '.html',
  '.md',
  '.webmanifest',
  '.txt',
]);

const LANGUAGE = {
  '.ts': 'ts',
  '.tsx': 'tsx',
  '.js': 'js',
  '.mjs': 'js',
  '.json': 'json',
  '.css': 'css',
  '.html': 'html',
  '.md': 'md',
  '.webmanifest': 'json',
  '.txt': 'text',
};

function languageFor(name) {
  // Files with no extension but a known name get something sensible.
  if (name === 'Dockerfile') return 'dockerfile';
  return LANGUAGE[extname(name)] ?? 'text';
}

function walk(dir, out = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }

  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (SKIP.has(entry.name)) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

function collect() {
  const files = [];

  for (const name of ROOT_FILES) {
    const full = join(ROOT, name);
    try {
      if (statSync(full).isFile()) files.push(full);
    } catch {
      /* optional file */
    }
  }

  for (const dir of DIRS) walk(join(ROOT, dir), files);

  return files.filter((file) => {
    if (SKIP.has(file.split(sep).pop())) return false;
    return TEXT_EXTENSIONS.has(extname(file));
  });
}

const files = collect();
const sections = [];
const contents = [];

for (const file of files) {
  const path = relative(ROOT, file).split(sep).join('/');
  const body = readFileSync(file, 'utf8');
  const lines = body.split('\n').length;
  contents.push({ path, lines });
  // Four backticks so fenced blocks inside markdown survive.
  sections.push(
    `### \`${path}\`\n\n\`\`\`\`${languageFor(file)}\n${body.replace(/\s*$/, '')}\n\`\`\`\`\n`,
  );
}

const total = contents.reduce((sum, entry) => sum + entry.lines, 0);

const header = [
  '# Images to PDF — complete source',
  '',
  `Generated by \`npm run bundle\`. ${contents.length} files, ${total.toLocaleString()} lines.`,
  '',
  'This is every source file in the project in one place: the app, the tests, the build',
  'config and the PWA assets. It is generated — edit the real files under `src/`, not this.',
  '',
  '## Contents',
  '',
  ...contents.map((entry) => `- \`${entry.path}\` (${entry.lines} lines)`),
  '',
  '---',
  '',
].join('\n');

writeFileSync(OUT, header + sections.join('\n'), 'utf8');
console.log(`CODE.md  ${contents.length} files, ${total.toLocaleString()} lines, ${Math.round(statSync(OUT).size / 1024)} KB`);
